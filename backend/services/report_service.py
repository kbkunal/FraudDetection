"""
ReportLab PDF Generation Service for CyberShield.
Generates structured incident and analysis reports with clear disclaimers,
provenance information, and indicators.
"""

from __future__ import annotations

import io
from datetime import datetime, timezone
from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    HRFlowable,
)


def _get_base_styles():
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "ReportTitle",
        parent=styles["Heading1"],
        fontName="Helvetica-Bold",
        fontSize=18,
        leading=22,
        textColor=colors.HexColor("#0D3475"),
    )
    subtitle_style = ParagraphStyle(
        "ReportSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#657184"),
    )
    section_heading = ParagraphStyle(
        "SectionHeading",
        parent=styles["Heading2"],
        fontName="Helvetica-Bold",
        fontSize=12,
        leading=16,
        textColor=colors.HexColor("#17202B"),
        spaceBefore=12,
        spaceAfter=6,
    )
    body_style = ParagraphStyle(
        "ReportBody",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=13,
        textColor=colors.HexColor("#17202B"),
    )
    disclaimer_style = ParagraphStyle(
        "ReportDisclaimer",
        parent=styles["Normal"],
        fontName="Helvetica-Oblique",
        fontSize=8,
        leading=11,
        textColor=colors.HexColor("#8791A0"),
    )
    return styles, title_style, subtitle_style, section_heading, body_style, disclaimer_style


def _build_header_elements(title: str, subtitle: str, ref_id: str):
    _, title_style, subtitle_style, _, body_style, _ = _get_base_styles()
    now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    elements = [
        Paragraph("CYBERSHIELD | Cyber Fraud & Financial Intelligence", subtitle_style),
        Paragraph(title, title_style),
        Spacer(1, 4),
        Paragraph(f"Reference ID: {ref_id}  |  Generated: {now_str}", subtitle_style),
        Spacer(1, 8),
        HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#1457C5"), spaceAfter=12),
        Paragraph(
            "<b>NOTICE:</b> This document is a user-prepared informational analysis generated by the CyberShield prototype. "
            "It does not constitute an official police complaint, legal evidence, or proof of guilt. "
            "To report an active cybercrime, contact India's National Cyber Crime Helpline at 1930 or visit cybercrime.gov.in.",
            body_style,
        ),
        Spacer(1, 10),
    ]
    return elements


def generate_upi_pdf(analysis_id: str, indicators: list, transactions: list) -> bytes:
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=letter, leftMargin=36, rightMargin=36, topMargin=36, bottomMargin=36)
    _, _, _, section_heading, body_style, disclaimer_style = _get_base_styles()

    elements = _build_header_elements("UPI Transaction Fraud Analysis Report", "Module 1: Payment Pattern Analysis", analysis_id)

    # Section 1: Indicators
    elements.append(Paragraph("1. Detected Review Indicators", section_heading))
    if indicators:
        ind_data = [["Code / Severity", "Explanation", "Method"]]
        for ind in indicators:
            sev = ind.get("severity", "medium").upper()
            code = ind.get("code", "")
            exp = ind.get("explanation", "")
            meth = ind.get("method", "rule")
            ind_data.append([
                Paragraph(f"<b>{code}</b><br/>[{sev}]", body_style),
                Paragraph(exp, body_style),
                Paragraph(meth, body_style),
            ])
        t_ind = Table(ind_data, colWidths=[120, 320, 100])
        t_ind.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EAF1FC")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.HexColor("#0D3475")),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, 0), 9),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ("TOPPADDING", (0, 0), (-1, -1), 6),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#DCE1E8")),
        ]))
        elements.append(t_ind)
    else:
        elements.append(Paragraph("No configured indicators were detected in the submitted data.", body_style))

    elements.append(Spacer(1, 12))

    # Section 2: Submitted Transactions
    elements.append(Paragraph("2. Submitted Transactions Summary", section_heading))
    if transactions:
        tx_data = [["Ref / UTR", "Timestamp", "Amount", "Sender", "Recipient", "Status"]]
        for tx in transactions[:15]:  # Up to 15 in summary
            tx_data.append([
                Paragraph(str(tx.get("transaction_ref") or "N/A"), body_style),
                Paragraph(str(tx.get("timestamp") or "")[:16], body_style),
                Paragraph(f"INR {tx.get('amount', 0):,.2f}", body_style),
                Paragraph(str(tx.get("sender_upi") or "")[:15], body_style),
                Paragraph(str(tx.get("recipient_upi") or "")[:15], body_style),
                Paragraph(str(tx.get("status") or ""), body_style),
            ])
        t_tx = Table(tx_data, colWidths=[90, 95, 75, 100, 100, 80])
        t_tx.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F4F6F9")),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, 0), 8),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#DCE1E8")),
        ]))
        elements.append(t_tx)

    elements.append(Spacer(1, 14))
    elements.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#DCE1E8"), spaceAfter=8))
    elements.append(Paragraph("Limitations: CyberShield cannot verify live NPCI or bank records. Review indicators prioritize investigation and do not establish legal liability.", disclaimer_style))

    doc.build(elements)
    return buffer.getvalue()


def generate_message_pdf(analysis_id: str, data: dict) -> bytes:
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=letter, leftMargin=36, rightMargin=36, topMargin=36, bottomMargin=36)
    _, _, _, section_heading, body_style, disclaimer_style = _get_base_styles()

    elements = _build_header_elements("Message Fraud Analysis Report", "Module 2: SMS & Messaging Smishing Analysis", analysis_id)

    # Assessment
    assessment = data.get("overall_assessment", "unknown").upper()
    elements.append(Paragraph(f"Overall Risk Assessment: <b>{assessment}</b>", section_heading))
    categories = ", ".join(data.get("categories", [])) or "None"
    elements.append(Paragraph(f"<b>Estimated Categories:</b> {categories}", body_style))
    elements.append(Spacer(1, 8))

    # Indicators
    indicators = data.get("indicators", [])
    elements.append(Paragraph("Detected Suspicious Indicators", section_heading))
    if indicators:
        ind_data = [["Code / Severity", "Explanation", "Evidence"]]
        for ind in indicators:
            ind_data.append([
                Paragraph(f"<b>{ind.get('code')}</b><br/>[{ind.get('severity', '').upper()}]", body_style),
                Paragraph(ind.get("explanation", ""), body_style),
                Paragraph(ind.get("evidence_reference", "") or "Text pattern", body_style),
            ])
        t_ind = Table(ind_data, colWidths=[130, 270, 140])
        t_ind.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EAF1FC")),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#DCE1E8")),
            ("TOPPADDING", (0, 0), (-1, -1), 5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ]))
        elements.append(t_ind)
    else:
        elements.append(Paragraph("No configured indicators were detected in the text.", body_style))

    elements.append(Spacer(1, 14))
    elements.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#DCE1E8"), spaceAfter=8))
    elements.append(Paragraph("Limitations: Sender ID cannot be verified without telecom carrier data. Phishing filters can produce false positives on standard alerts.", disclaimer_style))

    doc.build(elements)
    return buffer.getvalue()


def generate_email_pdf(analysis_id: str, data: dict) -> bytes:
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=letter, leftMargin=36, rightMargin=36, topMargin=36, bottomMargin=36)
    _, _, _, section_heading, body_style, disclaimer_style = _get_base_styles()

    elements = _build_header_elements("Email Phishing Analysis Report", "Module 3: Email & Header Forensic Analysis", analysis_id)

    assessment = data.get("overall_assessment", "unknown").upper()
    elements.append(Paragraph(f"Overall Risk Assessment: <b>{assessment}</b>", section_heading))

    # Sender Analysis
    sender = data.get("sender_analysis", {})
    elements.append(Paragraph("Sender & Domain Verification", section_heading))
    sender_data = [
        ["From Address", sender.get("from_address") or "N/A"],
        ["Reply-To", sender.get("reply_to") or "None specified"],
        ["Domain Match Status", sender.get("domain_match", "unknown")],
        ["Lookalike Detected", "YES" if sender.get("lookalike_domain_detected") else "No"],
    ]
    t_sender = Table(sender_data, colWidths=[180, 360])
    t_sender.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#DCE1E8")),
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#F4F6F9")),
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    elements.append(t_sender)
    elements.append(Spacer(1, 8))

    # Auth Results
    auth = data.get("auth_results", {})
    elements.append(Paragraph("Authentication Headers (SPF / DKIM / DMARC)", section_heading))
    auth_data = [
        ["SPF Check", auth.get("spf", "not_available").upper()],
        ["DKIM Check", auth.get("dkim", "not_available").upper()],
        ["DMARC Check", auth.get("dmarc", "not_available").upper()],
    ]
    t_auth = Table(auth_data, colWidths=[180, 360])
    t_auth.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#DCE1E8")),
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#F4F6F9")),
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    elements.append(t_auth)

    elements.append(Spacer(1, 14))
    elements.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#DCE1E8"), spaceAfter=8))
    elements.append(Paragraph("Limitations: Authentication results are extracted from uploaded headers; DKIM passing does not guarantee benign intent.", disclaimer_style))

    doc.build(elements)
    return buffer.getvalue()


def generate_incident_pdf(summary_data: dict) -> bytes:
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=letter, leftMargin=36, rightMargin=36, topMargin=36, bottomMargin=36)
    _, _, _, section_heading, body_style, disclaimer_style = _get_base_styles()

    ref_id = summary_data.get("id") or "INC-" + datetime.now(timezone.utc).strftime("%Y%m%d%H%M")
    elements = _build_header_elements("User-Prepared Incident Summary", "Fraud Victim Help Centre — Complaint Preparation Dossier", ref_id)

    # Narrative & Metadata Table
    meta_data = [
        ["Incident Category", summary_data.get("category", "N/A")],
        ["Incident Date", summary_data.get("incident_date") or "Unspecified"],
        ["Financial Loss", f"INR {summary_data.get('loss_amount', 0):,.2f}" if summary_data.get('loss_amount') else "None reported"],
        ["Payment Method", summary_data.get("payment_method") or "N/A"],
        ["Transaction Reference / UTR", summary_data.get("transaction_ref") or "N/A"],
        ["Existing Complaint Refs", summary_data.get("complaint_refs") or "None"],
    ]
    t_meta = Table(meta_data, colWidths=[180, 360])
    t_meta.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#DCE1E8")),
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#F4F6F9")),
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    elements.append(t_meta)
    elements.append(Spacer(1, 10))

    # User Narrative
    elements.append(Paragraph("Incident Narrative (User-Provided Statement)", section_heading))
    elements.append(Paragraph(summary_data.get("narrative", "No narrative provided."), body_style))
    elements.append(Spacer(1, 10))

    # Evidence Notes
    if summary_data.get("evidence_notes"):
        elements.append(Paragraph("Evidence Preserved by User", section_heading))
        elements.append(Paragraph(summary_data.get("evidence_notes", ""), body_style))
        elements.append(Spacer(1, 10))

    elements.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#DCE1E8"), spaceAfter=8))
    elements.append(Paragraph("This document organizes your incident facts to facilitate filing on cybercrime.gov.in or presenting to your bank.", disclaimer_style))

    doc.build(elements)
    return buffer.getvalue()
